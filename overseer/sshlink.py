"""Overseer's own SSH setup: key, config and known_hosts live in the Overseer folder.

Layout (defaults):

    ./state/ssh/id_ed25519(.pub)   Overseer's key (generated or imported) - never readable by the agent
    ./state/ssh/known_hosts
    ./state/ssh/config             used by Overseer; ControlMaster keeps ONE connection to the HPC open
    /tmp/overseer/ssh/master.sock  the multiplexed connection
    /tmp/overseer/agent-ssh/config used by the agent: no key, only the master socket
    /tmp/overseer/agent-bin/ssh    wrappers (ssh/scp/sftp) so `ssh hpc` just works for the agent

The agent therefore reaches the HPC only through the connection Overseer holds open; it
never sees the key or your ~/.ssh, and its sandbox needs no network access for it.
"""

from __future__ import annotations

import asyncio
import os
import shutil
import stat
import subprocess
from pathlib import Path

from .config import Config, ConfigError

WRAPPED = ("ssh", "scp", "sftp")


def _q(value: str | Path) -> str:
    s = str(value)
    if any(c in s for c in ' "\t'):
        return '"' + s.replace('"', '\\"') + '"'
    return s


def real_binary(name: str, cfg: Config) -> str:
    """The system ssh/scp/sftp (not our wrapper)."""
    bin_dir = str(cfg.local.tmp("agent-bin"))
    path = os.pathsep.join(p for p in os.environ.get("PATH", "").split(os.pathsep) if p and p != bin_dir)
    found = shutil.which(name, path=path)
    if not found:
        raise ConfigError(f"{name!r} not found on PATH; install OpenSSH client")
    return found


def overseer_ssh_config(cfg: Config) -> str:
    s = cfg.ssh
    lines = [
        "# Generated by Overseer - edit config.yaml (ssh:) instead.",
        "Host *",
        f"  IdentityFile {_q(cfg.ssh_key)}",
        "  IdentitiesOnly yes",
        f"  UserKnownHostsFile {_q(cfg.ssh_dir / 'known_hosts')}",
        "  StrictHostKeyChecking accept-new",
        "  BatchMode yes",
        "  ServerAliveInterval 30",
        "  ServerAliveCountMax 4",
        f"  ConnectTimeout {s.connect_timeout}",
        "",
        f"Host {s.host}",
        f"  HostName {s.hostname}",
        f"  Port {s.port}",
    ]
    if s.user:
        lines.append(f"  User {s.user}")
    if s.proxy_jump:
        lines.append(f"  ProxyJump {s.proxy_jump}")
    lines += [
        "  ControlMaster auto",
        f"  ControlPath {_q(cfg.control_socket)}",
        "  ControlPersist yes",
    ]
    for k, v in s.extra_options.items():
        lines.append(f"  {k} {v}")
    return "\n".join(lines) + "\n"


def agent_ssh_config(cfg: Config) -> str:
    s = cfg.ssh
    lines = [
        "# Generated by Overseer. The agent reaches the HPC only through Overseer's master connection.",
        f"Host {s.host}",
        f"  HostName {s.hostname}",
        f"  Port {s.port}",
    ]
    if s.user:
        lines.append(f"  User {s.user}")
    lines += [
        "  ControlMaster no",
        f"  ControlPath {_q(cfg.control_socket)}",
        "  BatchMode yes",
        "  IdentityFile none",
        "  StrictHostKeyChecking no",
        "  UserKnownHostsFile /dev/null",
        "  LogLevel ERROR",
    ]
    return "\n".join(lines) + "\n"


def _write(path: Path, content: str, mode: int) -> None:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w") as fh:
        fh.write(content)
    os.chmod(path, mode)


def write_configs(cfg: Config) -> None:
    """(Re)generate both ssh configs and the agent's ssh/scp/sftp wrappers."""
    cfg.ssh_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(cfg.ssh_dir, 0o700)
    cfg.control_socket.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    _write(cfg.ssh_config_file, overseer_ssh_config(cfg), 0o600)
    _write(cfg.agent_ssh_config, agent_ssh_config(cfg), 0o600)
    bin_dir = cfg.local.tmp("agent-bin")
    for name in WRAPPED:
        _write(bin_dir / name, f'#!/bin/sh\nexec {_q(real_binary(name, cfg))} -F {_q(cfg.agent_ssh_config)} "$@"\n', 0o700)
    # ssh again, with the login-node CPU limit, and hpc-run (see compute.py)
    from .compute import write_agent_tools
    write_agent_tools(cfg, bin_dir, real_binary("ssh", cfg), _write)


def agent_bin_dir(cfg: Config) -> Path:
    return cfg.local.tmp("agent-bin")


def base_argv(cfg: Config) -> list[str]:
    """How Overseer itself invokes ssh."""
    return [real_binary("ssh", cfg), "-F", str(cfg.ssh_config_file)]


# ---------------------------------------------------------------------------- key setup

def setup_key(cfg: Config, import_from: str | None = None) -> str:
    """Create (or import) Overseer's key. Returns the public key line."""
    write_configs(cfg)
    key = cfg.ssh_key
    if import_from:
        src = Path(import_from).expanduser()
        if not src.is_file():
            raise ConfigError(f"{src} does not exist")
        shutil.copyfile(src, key)
        os.chmod(key, 0o600)
        if Path(str(src) + ".pub").is_file():
            shutil.copyfile(str(src) + ".pub", str(key) + ".pub")
        else:
            pub = subprocess.run(["ssh-keygen", "-y", "-f", str(key)], capture_output=True, text=True, check=True).stdout
            _write(Path(str(key) + ".pub"), pub, 0o644)
    elif not key.exists():
        subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "overseer", "-f", str(key)], check=True)
    os.chmod(key, 0o600)
    return Path(str(key) + ".pub").read_text().strip()


# ---------------------------------------------------------------------------- master connection

async def _run(argv: list[str], timeout: float) -> tuple[int, str]:
    proc = await asyncio.create_subprocess_exec(
        *argv, stdin=asyncio.subprocess.DEVNULL, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT)
    try:
        out, _ = await asyncio.wait_for(proc.communicate(), timeout)
    except asyncio.TimeoutError:
        proc.kill()
        await proc.wait()
        return -1, "timed out"
    return proc.returncode or 0, out.decode(errors="replace").strip()


async def master_alive(cfg: Config) -> bool:
    rc, _ = await _run([*base_argv(cfg), "-O", "check", cfg.ssh.host], 10)
    return rc == 0


async def ensure_master(cfg: Config) -> None:
    """Make sure the multiplexed connection the agent uses is up."""
    if await master_alive(cfg):
        return
    write_configs(cfg)
    rc, out = await _run([*base_argv(cfg), "-f", "-N", cfg.ssh.host], cfg.ssh.connect_timeout + 30)
    if rc != 0 or not await master_alive(cfg):
        raise ConfigError(f"could not open the SSH connection to {cfg.ssh.hostname}: {out[-500:]}")


def connect_interactive(cfg: Config) -> int:
    """Open the master connection with prompts allowed (for clusters that need 2FA once)."""
    write_configs(cfg)
    argv = [*base_argv(cfg), "-o", "BatchMode=no", "-f", "-N", cfg.ssh.host]
    return subprocess.call(argv)


def key_permissions_ok(cfg: Config) -> bool:
    try:
        return stat.S_IMODE(cfg.ssh_key.stat().st_mode) & 0o077 == 0
    except FileNotFoundError:
        return False
